public class RightShift {
    public static void main(String[] args) {
        int n = 13;
        System.out.println(n >> 1);
        int n1 = -13;
        System.out.println(n1 >> 1);
        int a = -22;
        System.out.println(a >> 2);
        int b = -1;
        System.out.println(b >> 2);
    }
}
